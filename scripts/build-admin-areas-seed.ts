// Generates supabase/seed/01_admin_areas.sql from the simplified COD-AB GeoJSON files.
// Run: bun scripts/build-admin-areas-seed.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Props = Record<string, string>;
type Feature = { properties: Props; geometry: unknown };

const root = join(import.meta.dir, '..');
const read = (name: string): Feature[] =>
  JSON.parse(readFileSync(join(root, 'supabase/data', name), 'utf8')).features;

// Provinces TH30–TH49 form the northeast (Isan); see supabase/data/SOURCE.md.
export function regionOf(adm1Pcode: string): 'isan' | 'other' {
  const n = Number(adm1Pcode.slice(2));
  return n >= 30 && n <= 49 ? 'isan' : 'other';
}

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

type Row = { level: 1 | 2; pcode: string; nameTh: string; nameEn: string; provinceTh: string; adm1: string; geometry: unknown };

const rows: Row[] = [
  ...read('tha_adm1.geojson').map((f) => ({
    level: 1 as const,
    pcode: f.properties.ADM1_PCODE,
    nameTh: f.properties.ADM1_TH,
    nameEn: f.properties.ADM1_EN,
    provinceTh: f.properties.ADM1_TH,
    adm1: f.properties.ADM1_PCODE,
    geometry: f.geometry,
  })),
  ...read('tha_adm2.geojson').map((f) => ({
    level: 2 as const,
    pcode: f.properties.ADM2_PCODE,
    nameTh: f.properties.ADM2_TH,
    nameEn: f.properties.ADM2_EN,
    provinceTh: f.properties.ADM1_TH,
    adm1: f.properties.ADM1_PCODE,
    geometry: f.geometry,
  })),
];

const out: string[] = ['-- Generated by scripts/build-admin-areas-seed.ts. Do not edit by hand.'];
for (let i = 0; i < rows.length; i += 50) {
  const values = rows.slice(i, i + 50).map(
    (r) =>
      `(${r.level}, ${q(r.pcode)}, ${q(r.nameTh)}, ${q(r.nameEn)}, ${q(r.provinceTh)}, ${q(regionOf(r.adm1))}, ` +
      `extensions.st_multi(extensions.st_geomfromgeojson(${q(JSON.stringify(r.geometry))}))::extensions.geography)`,
  );
  out.push(
    `insert into public.admin_areas (level, pcode, name_th, name_en, province_th, region, geom) values\n${values.join(',\n')};`,
  );
}

mkdirSync(join(root, 'supabase/seed'), { recursive: true });
writeFileSync(join(root, 'supabase/seed/01_admin_areas.sql'), out.join('\n\n') + '\n');
console.log(`wrote ${rows.length} admin areas`);
